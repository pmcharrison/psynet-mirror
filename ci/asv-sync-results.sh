#!/usr/bin/env bash
# Sync ASV benchmark results with the `benchmark-results` orphan branch.
#
# Bootstraps the branch on first run, attaches it as a git worktree at
# `.asv/results/`, runs `asv run` (forwarding any arguments), commits any
# new result files back to the branch, then detaches the worktree.
#
# Pass `--init-only` to just ensure the branch exists and exit.
# Push manually after running: `git push <remote> benchmark-results`.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RESULTS_DIR="$REPO_ROOT/.asv/results"
BRANCH="benchmark-results"
REMOTE="${ASV_RESULTS_REMOTE:-origin}"
ATTACHED=0

cd "$REPO_ROOT"

git config user.email >/dev/null || { echo "git user.email not set" >&2; exit 1; }
git config user.name >/dev/null || { echo "git user.name not set" >&2; exit 1; }

ensure_branch() {
    if git show-ref --verify --quiet "refs/heads/$BRANCH"; then
        return
    fi
    if git ls-remote --exit-code --heads "$REMOTE" "$BRANCH" >/dev/null 2>&1; then
        git fetch "$REMOTE" "$BRANCH:$BRANCH"
        return
    fi
    local blob tree commit
    blob=$(printf 'ASV benchmark results — generated by ci/asv-sync-results.sh, do not edit by hand.\n' | git hash-object -w --stdin)
    tree=$(printf '100644 blob %s\tREADME.md\n' "$blob" | git mktree)
    commit=$(git commit-tree -m "Initialize $BRANCH for ASV results" "$tree")
    git branch "$BRANCH" "$commit"
    echo "Created local orphan branch $BRANCH"
}

attach_worktree() {
    if [ -e "$RESULTS_DIR/.git" ]; then
        local current
        current=$(git -C "$RESULTS_DIR" rev-parse --abbrev-ref HEAD)
        if [ "$current" = "HEAD" ]; then
            echo "Error: $RESULTS_DIR is in detached-HEAD state, expected branch '$BRANCH'" >&2
            exit 1
        fi
        if [ "$current" != "$BRANCH" ]; then
            echo "Error: $RESULTS_DIR is checked out to '$current', expected '$BRANCH'" >&2
            exit 1
        fi
        ATTACHED=1
        return
    fi
    if [ -e "$RESULTS_DIR" ]; then
        rm -rf "$RESULTS_DIR"
    fi
    mkdir -p "$(dirname "$RESULTS_DIR")"
    git worktree add "$RESULTS_DIR" "$BRANCH"
    ATTACHED=1
}

detach_worktree() {
    [ "$ATTACHED" = "1" ] || return
    if [ -e "$RESULTS_DIR/.git" ]; then
        if ! git worktree remove "$RESULTS_DIR" 2>/dev/null; then
            echo "Worktree at $RESULTS_DIR has uncommitted changes; leaving in place" >&2
            echo "Inspect with: git -C $RESULTS_DIR status" >&2
        fi
    fi
}

ensure_branch

if [ "${1:-}" = "--init-only" ]; then
    echo "Branch $BRANCH ready"
    exit 0
fi

trap detach_worktree EXIT
attach_worktree

asv run "$@"

cd "$RESULTS_DIR"
if [ -n "$(git status --porcelain)" ]; then
    git add -A
    PRE_COMMIT_ALLOW_NO_CONFIG=1 git commit -m "asv: results from $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "Committed new results to $BRANCH (push with: git push $REMOTE $BRANCH)"
else
    echo "No new results to commit"
fi
